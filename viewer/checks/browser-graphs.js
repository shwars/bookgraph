 await page.getByRole('combobox',{name:'Роль в сюжете',exact:true}).selectOption('main');
 check(await page.locator('#graph .node').count()===6,'main cast importance filter');
 await page.locator('#graph [data-id="Лариса Огудалова"]').focus();
