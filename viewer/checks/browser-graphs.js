 check(await page.locator('#graph .node.event').count()>3,'act and participant filters');
 const ids=await page.locator('#graph .node').evaluateAll(es=>es.map(e=>e.dataset.id));
 check(new Set(ids).size===ids.length,'no duplicate event nodes');
