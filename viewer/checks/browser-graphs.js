 await page.setViewportSize({width:390,height:844});
 await page.getByRole('searchbox').fill('Лариса Дмитриевна');
 await page.locator('[data-search-id="Лариса Огудалова"]').click();
 check(await page.locator('#inspector').isVisible(),'mobile drawer');
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no horizontal page overflow');
 await page.screenshot({path:'output/playwright/mobile.png'});
